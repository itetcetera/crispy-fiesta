    /// <summary>A species' map walker frames as the game copies them for a player ($0E00 + 128 per player): the
    /// disk's 82 bytes, the rest clear.</summary>
    public static byte[] WalkerMap(Race race) => Padded(SpeciesFrames.Map[(int)race], 0x80);

    /// <summary>A species' town walker frames as the game copies them ($09C0 + $110 per player).</summary>
    public static byte[] WalkerTown(Race race) => Padded(SpeciesFrames.Town[(int)race], 0x110);

    static byte[] Padded(byte[] b, int length)
    {
        var r = new byte[length];
        b.CopyTo(r, 0);
        return r;
    }
