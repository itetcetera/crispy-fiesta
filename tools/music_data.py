"""Reads the music player's data from the original disk image and writes
server/Mule.Engine/Rules/MusicData.cs.

The player ($2527 to $2D42) keeps its tables, its working bytes and its four voices' notes in one block,
$24A0 to $2CE0, which the disk holds in one piece (the snapshot's bytes at the same addresses match):
  $24A0-$24A6  the start offset, the song length, the end address and the playing flag
  $24A7-$24AA  each voice's starting volume and distortion (AUDC)
  $24AB-$24C8  voice 1's note frequencies; $24C9-$24F9 voices 2 and 3's
  $24FA-$251E  the working envelope: volume, hold, decay, length and the playing flag per voice
  $251F-$2526  the song length by round / 4
  $28B2, $29D3, $2B58, $2CD0  the voices' notes (voice 4: frequencies only)

    python3 tools/music_data.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ATR = os.path.join(ROOT, "reference", "M.U.L.E. (1983) Electronic Arts US.atr")
OUT = os.path.join(ROOT, "server", "Mule.Engine", "Rules", "MusicData.cs")
START, END = 0x24A0, 0x2CE1
DISK = 56352  # where $24A0 sits in the disk's data (after the 16-byte header)

disk = open(ATR, "rb").read()[16:]
data = disk[DISK:DISK + END - START]

out = [
    "// Generated by tools/music_data.py from the original disk image. Do not edit.",
    "namespace Mule.Engine.Rules;",
    "",
    "/// <summary>The music player's block as the disk holds it, $24A0 to $2CE0: tables, working bytes and notes.</summary>",
    "public static class MusicData",
    "{",
    "    public const int Start = 0x%04X;" % START,
    "",
    "    public static readonly byte[] Image =",
    "    {",
]
for i in range(0, len(data), 16):
    out.append("        " + " ".join("0x%02X," % b for b in data[i:i + 16]) + "  // $%04X" % (START + i))
out += ["    };", "}"]
with open(OUT, "w") as fh:
    fh.write("\n".join(out) + "\n")
print("wrote", OUT, len(data))
