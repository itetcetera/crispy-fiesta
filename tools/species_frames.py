"""Reads the eight species' walker frames from the original disk image and writes:
  - server/Mule.Engine/Rules/SpeciesFrames.cs (the frames the game copies for each player), and
  - client/public/assets/walker-<species>.png (the town's front-facing frame, as a placeholder picture).

The disk boots its first 129 sectors to $7BEF (the boot header). The species setup ($86B5) reads the race
from $840B and copies two pointers per race into each player's slots: $844C (map frames, to $0911) and
$843C (town frames, to $0909). The game later copies 82 bytes of map frames and 264 of town frames,
which is what the snapshot holds for its Mechtron and Bonzoid ($0E00/$0F80 and $09C0/$0CF0).

    python3 tools/species_frames.py
"""
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ATR = os.path.join(ROOT, "reference", "M.U.L.E. (1983) Electronic Arts US.atr")
LOAD = 0x7BEF
MAP_TABLE, TOWN_TABLE = 0x844C, 0x843C
MAP_BYTES, TOWN_BYTES = 82, 264
NAMES = ["Mechtron", "Gollumer", "Packer", "Bonzoid", "Spheroid", "Flapper", "Leggite", "Humanoid"]

disk = open(ATR, "rb").read()[16:]
mem = lambda a, n: disk[a - LOAD:a - LOAD + n]
word = lambda a: struct.unpack("<H", mem(a, 2))[0]


def frames():
    for race, name in enumerate(NAMES):
        m, t = word(MAP_TABLE + 2 * race), word(TOWN_TABLE + 2 * race)
        yield name, m, mem(m, MAP_BYTES), t, mem(t, TOWN_BYTES)


def cs_bytes(b, indent="        "):
    rows = [", ".join(f"0x{x:02X}" for x in b[i:i + 16]) for i in range(0, len(b), 16)]
    return "".join(f"{indent}{r},\n" for r in rows)


def write_cs():
    out = [
        "// Generated by tools/species_frames.py from the original disk image. Do not edit.",
        "namespace Mule.Engine.Rules;",
        "",
        "/// <summary>The species' walker frames as the disk holds them (the boot image at $7BEF): the map frames",
        "/// (82 bytes, from the table at $844C) and the town frames (264 bytes, from $843C), by race.</summary>",
        "public static class SpeciesFrames",
        "{",
    ]
    for kind, idx in (("Map", 2), ("Town", 4)):
        out.append(f"    public static readonly byte[][] {kind} =")
        out.append("    {")
        for f in frames():
            out.append(f"        // {f[0]} (${f[idx - 1]:04X})")
            out.append("        new byte[]")
            out.append("        {")
            out.append(cs_bytes(f[idx], "            ").rstrip("\n"))
            out.append("        },")
        out.append("    };")
        out.append("")
    out[-1] = "}"
    path = os.path.join(ROOT, "server", "Mule.Engine", "Rules", "SpeciesFrames.cs")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")


def write_png():
    from PIL import Image
    # The town's front-facing frame (anim $60): 8 pixels wide, rows 3-20 (byte 0 is a flag, not a row).
    for name, _, _, _, t in frames():
        rows = t[0x60 + 3:0x60 + 21]
        img = Image.new("RGBA", (8, len(rows)), (0, 0, 0, 0))
        for y, b in enumerate(rows):
            for x in range(8):
                if b & (0x80 >> x):
                    img.putpixel((x, y), (255, 255, 255, 255))
        # 4 canvas pixels a colour clock, 2 a scanline, and twice that for sharpness.
        img = img.resize((8 * 8, len(rows) * 4), Image.NEAREST)
        img.save(os.path.join(ROOT, "client", "public", "assets", f"walker-{name.lower()}.png"))


write_cs()
write_png()
